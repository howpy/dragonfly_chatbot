// Execute against an explicitly supplied official runtime, never a user profile.
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const plugin = await import(process.argv[3] ? pathToFileURL(resolve(process.argv[3])).href : new URL('../src/index.mjs', import.meta.url).href);
const modules = resolve(process.argv[2] || '../../.tmp/dsh-dragonfly-runtime/node_modules');
const load = name => import(pathToFileURL(resolve(modules, '@deepseek-ai', name, 'lib/index.js')).href);
const {Context} = await load('cordis');
const {SystemPrompt, renderPrompt} = await load('dsh-system-prompt');
const {ToolRuntime} = await load('dsh-tools');
const ctx = new Context();
await ctx.plugin(SystemPrompt, {}).await();
await ctx.plugin(ToolRuntime, {mode: 'native'}).await();
const fork = ctx.plugin(plugin, {});
await fork.await();
assert.equal(ctx.tools.schemas().length, 4);
const controller = new AbortController();
const run = (name, args) => ctx.tools.execute({callId: `verify-${name}`, name, arguments: args, signal: controller.signal});
const status = await run('get_dragonfly_corpus_status', {});
assert.equal(status.isError, false, JSON.stringify(status));
const search = await run('search_dragonfly_knowledge', {query: 'threshold segmentation'});
assert.ok(!search.isError, JSON.stringify(search));
const hit = JSON.parse(search.content.find(c => c.type === 'text').text).hits[0];
assert.ok(hit.id);
const read = await run('read_dragonfly_evidence', {id: hit.id});
assert.ok(!read.isError, JSON.stringify(read));
const invalid = await run('read_dragonfly_evidence', {id: '../private'});
assert.ok(invalid.isError);
const assembly = await ctx.systemPrompt.assemble();
assert.match(renderPrompt(assembly), /dragonfly_chatbot/);
assert.equal(assembly.tools.length, 4);
await fork.dispose();
assert.equal(ctx.tools.schemas().length, 0);
const clean = await ctx.systemPrompt.assemble();
assert.ok(!renderPrompt(clean).includes('dragonfly_chatbot'));
console.log(JSON.stringify({runtime: '0.2.1-rc.2', tools: 4, tool_pipeline: 'passed', prompt_assembly: 'passed', unload: 'passed'}));
