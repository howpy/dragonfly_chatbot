import test from 'node:test';
import assert from 'node:assert/strict';
import { apply, Config, createKnowledge, createTools } from '../src/index.mjs';
import { detectEnvironment } from '../src/environment.mjs';
const empty = detectEnvironment({env:{}, scanRoots:[], registryEntries:[]});
test('help-only mode supplies an explicit notice, working help, no local source and strict versions', async () => {
  const knowledge = createKnowledge({}, empty);
  const tools = createTools(knowledge);
  assert.equal(tools.length, 4);
  const result = await tools[0].execute({query:'threshold segmentation', version:'2027.1'});
  assert.equal(result.mode, 'help_only');
  assert.match(result.notice, /not found/);
  assert.ok(result.hits.length);
  const evidence = await tools[2].execute({id:result.hits[0].id});
  assert.ok(evidence.text);
  assert.equal(evidence.version, '2027.1');
  assert.deepEqual((await tools[1].execute({query:'Channel'})).hits, []);
  assert.equal((await tools[3].execute({})).dragonfly_found, false);
  assert.deepEqual((await tools[0].execute({query:'threshold', version:'2099.1'})).hits, []);
  await assert.rejects(tools[2].execute({id:'../secret'}));
  await assert.rejects(tools[0].execute({query:'mesh', limit:100}));
  assert.throws(() => createTools(knowledge, 0));
});
test('activation registers four tools and scoped guidance; missing optional help fails', () => {
  const tools=[], sections=[];
  const ctx={tools:{register:t=>tools.push(t)}, systemPrompt:{section:s=>sections.push(s)}};
  apply(ctx, Config({}));
  assert.equal(tools.length,4);
  assert.equal(sections.length,1);
  assert.equal(sections[0].interpolate,false);
  assert.match(sections[0].text,/Dragonfly 3D World/);
  assert.ok(!sections[0].complete);
  assert.throws(() => createKnowledge({helpCorpusFile:'/does-not-exist/help.json'}, empty));
});
